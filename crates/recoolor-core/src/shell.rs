//! The GNOME Shell theme Recoolor writes: `$XDG_DATA_HOME/themes/Recoolor/gnome-shell/gnome-shell.css`,
//! loaded by the User Themes extension. Setting the extension's theme name is the
//! app's job; this module only writes and removes the file, never one Recoolor did not write.

use std::fs;
use std::path::{Path, PathBuf};

use crate::apply::{ApplyError, CssState, css_state, io_err, write_atomic};

/// The theme name to give the User Themes extension.
pub const THEME_NAME: &str = "Recoolor";

pub fn css_path(data_home: &Path) -> PathBuf {
    theme_dir(data_home).join("gnome-shell/gnome-shell.css")
}

fn theme_dir(data_home: &Path) -> PathBuf {
    data_home.join("themes").join(THEME_NAME)
}

pub fn status(data_home: &Path) -> Result<CssState, ApplyError> {
    css_state(&css_path(data_home))
}

pub fn write(data_home: &Path, css: &str) -> Result<(), ApplyError> {
    let path = css_path(data_home);
    if css_state(&path)? == CssState::Foreign {
        return Err(ApplyError::Foreign { path });
    }
    write_atomic(&path, css)
}

/// Removes Recoolor's stylesheet and the folders it leaves empty. Returns whether there
/// was one; anything else in the theme folder stays.
pub fn remove(data_home: &Path) -> Result<bool, ApplyError> {
    let path = css_path(data_home);
    match css_state(&path)? {
        CssState::Recoolor(_) | CssState::RecoolorPair { .. } => {
            fs::remove_file(&path).map_err(io_err(&path))?;
            // remove_dir only succeeds on empty folders, which is exactly what we want.
            let _ = fs::remove_dir(path.parent().expect("css has a parent"));
            let _ = fs::remove_dir(theme_dir(data_home));
            Ok(true)
        }
        CssState::Missing | CssState::Foreign => Ok(false),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const CSS: &str = "/* Generated by Recoolor: palette=dracula */\n#panel {}\n";

    #[test]
    fn write_and_remove_clean_up_only_recoolors_files() {
        let home = tempfile::tempdir().unwrap();
        write(home.path(), CSS).unwrap();
        assert_eq!(
            status(home.path()).unwrap(),
            CssState::Recoolor("dracula".into())
        );
        assert!(remove(home.path()).unwrap());
        assert!(!theme_dir(home.path()).exists());

        // Someone else's file in a folder that happens to be called Recoolor.
        let path = css_path(home.path());
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, "#panel { color: red; }").unwrap();
        assert!(matches!(
            write(home.path(), CSS),
            Err(ApplyError::Foreign { .. })
        ));
        assert!(!remove(home.path()).unwrap());
        assert!(path.exists());
    }
}
