//! Firefox and Thunderbird: `chrome/recoolor.css` in each profile sets the color
//! variables that firefox-gnome-theme (`--gnome-*`), Catppuccin-style userChrome
//! files (`--ctp-*`) and Thunderbird's own chrome (`--layout-*`) read, and one
//! marked `@import` line in `userChrome.css` loads it after them. Both read
//! userChrome at startup, so they need a restart after Apply; both also need
//! `toolkit.legacyUserProfileCustomizations.stylesheets` turned on. With a
//! light/dark pair the dark colors sit in a `prefers-color-scheme` query, which
//! Firefox evaluates live, so a light/dark switch needs no restart.

use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::{ApplyError, io_err, read_or_empty, write_atomic};
use crate::palette::Palette;

const IMPORT: &str = "@import \"recoolor.css\"; /* Added by Recoolor; Reset removes it. */";

/// Firefox's profile folders (`~/.mozilla/firefox`, `~/.config/mozilla/firefox`
/// used by newer releases, and Flathub's).
pub fn profiles(home: &Path) -> Vec<PathBuf> {
    profiles_in(&[
        home.join(".mozilla/firefox"),
        home.join(".config/mozilla/firefox"),
        home.join(".var/app/org.mozilla.firefox/.mozilla/firefox"),
    ])
}

/// Thunderbird's profile folders (the older `~/.thunderbird`, the XDG location
/// newer releases use, and Flathub's).
pub fn thunderbird_profiles(home: &Path) -> Vec<PathBuf> {
    profiles_in(&[
        home.join(".thunderbird"),
        home.join(".config/thunderbird"),
        home.join(".var/app/org.mozilla.Thunderbird/.thunderbird"),
    ])
}

/// Profile folders listed in each root's `profiles.ini`.
fn profiles_in(roots: &[PathBuf]) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for root in roots {
        let Ok(ini) = fs::read_to_string(root.join("profiles.ini")) else {
            continue;
        };
        for section in ini
            .split("\n[")
            .filter(|s| s.trim_start_matches('[').starts_with("Profile"))
        {
            let value = |key: &str| {
                section
                    .lines()
                    .find_map(|l| l.strip_prefix(key)?.strip_prefix('='))
                    .map(str::trim)
            };
            let Some(path) = value("Path") else { continue };
            let dir = if value("IsRelative") == Some("0") {
                PathBuf::from(path)
            } else {
                root.join(path)
            };
            if dir.is_dir() && !found.contains(&dir) {
                found.push(dir);
            }
        }
    }
    found
}

pub fn css_path(profile: &Path) -> PathBuf {
    profile.join("chrome/recoolor.css")
}

fn user_chrome(profile: &Path) -> PathBuf {
    profile.join("chrome/userChrome.css")
}

/// `palette`'s colors, or with `dark`, the light/dark pair: `palette` by
/// default and `dark` while the system (and so Firefox) is in dark style.
pub fn render(palette: &Palette, dark: Option<&Palette>) -> String {
    match dark {
        None => format!(
            "/* Generated by Recoolor from {} */\n{}",
            palette.id,
            variables(palette)
        ),
        Some(dark) => format!(
            "/* Generated by Recoolor from {} and {} */\n{}\n@media (prefers-color-scheme: dark) {{\n{}}}\n",
            palette.id,
            dark.id,
            variables(palette),
            variables(dark)
        ),
    }
}

