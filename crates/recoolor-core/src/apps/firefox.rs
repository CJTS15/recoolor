/// Adds the import after the file's existing `@import`s (CSS wants them first).
fn add_import(text: &str) -> String {
    if text.lines().any(|l| l.trim() == IMPORT) {
        return text.to_owned();
    }
    let mut lines: Vec<&str> = text.lines().collect();
    let at = lines
        .iter()
        .rposition(|l| l.trim_start().starts_with("@import"))
        .map_or(0, |i| i + 1);
    lines.insert(at, IMPORT);
    lines.join("\n") + "\n"
}

fn remove_import(text: &str) -> String {
    let kept: Vec<&str> = text.lines().filter(|l| l.trim() != IMPORT).collect();
    if kept.iter().all(|l| l.trim().is_empty()) {
        return String::new();
    }
    kept.join("\n") + "\n"
}

/// Whether the profile lets Firefox load `userChrome.css` at all.
pub fn stylesheets_enabled(profile: &Path) -> bool {
    const PREF: &str = "\"toolkit.legacyUserProfileCustomizations.stylesheets\", true)";
    ["prefs.js", "user.js"].iter().any(|f| {
        fs::read_to_string(profile.join(f)).is_ok_and(|text| text.lines().any(|l| l.contains(PREF)))
    })
}

pub fn is_applied(profile: &Path) -> bool {
    super::is_ours(&css_path(profile))
}

pub fn apply(profile: &Path, palette: &Palette, dark: Option<&Palette>) -> Result<(), ApplyError> {
    write_owned(&css_path(profile), &render(palette, dark))?;
    let path = user_chrome(profile);
    let text = read(&path)?;
    let with = add_import(&text);
    if with != text {
        write_atomic(&path, &with)?;
    }
    Ok(())
}

pub fn remove(profile: &Path) -> Result<(), ApplyError> {
    remove_owned(&css_path(profile))?;
    let path = user_chrome(profile);
    let text = read(&path)?;
    let without = remove_import(&text);
    if without == text {
        return Ok(());
    }
    if without.is_empty() {
        // Recoolor created this file to hold the import.
        return fs::remove_file(&path).map_err(io_err(&path));
    }
    write_atomic(&path, &without)
}

fn read(path: &Path) -> Result<String, ApplyError> {
    read_or_empty(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn import_goes_after_imports_and_comes_back_out() {
        let user = "@import \"firefox-gnome-theme/userChrome.css\";\n#nav-bar { color: red; }\n";
        let with = add_import(user);
        assert_eq!(
            with,
            format!(
                "@import \"firefox-gnome-theme/userChrome.css\";\n{IMPORT}\n#nav-bar {{ color: red; }}\n"
            )
        );
        assert_eq!(add_import(&with), with);
        assert_eq!(remove_import(&with), user);
        assert_eq!(remove_import(&add_import("")), "");
    }

    #[test]
    fn finds_relative_and_absolute_profiles() {
        let home = tempfile::tempdir().unwrap();
        let root = home.path().join(".mozilla/firefox");
        let abs = home.path().join("elsewhere");
        for dir in [root.join("a.default"), abs.clone()] {
            fs::create_dir_all(dir).unwrap();
        }
        fs::write(
            root.join("profiles.ini"),
            format!(
                "[Profile1]\nName=x\nIsRelative=1\nPath=a.default\n\n[Profile0]\nIsRelative=0\nPath={}\n\n[Profile2]\nIsRelative=1\nPath=missing\n\n[General]\nVersion=2\n",
                abs.display()
            ),
        )
        .unwrap();
        assert_eq!(profiles(home.path()), [root.join("a.default"), abs]);

        let tb = home.path().join(".thunderbird");
        fs::create_dir_all(tb.join("x.default-release")).unwrap();
        fs::write(
            tb.join("profiles.ini"),
            "[Profile0]\nIsRelative=1\nPath=x.default-release\n",
        )
        .unwrap();
        assert_eq!(
            thunderbird_profiles(home.path()),
            [tb.join("x.default-release")]
        );
    }

    #[test]
    fn a_pair_switches_with_the_system_style() {
        let find = |id: &str| bundled().into_iter().find(|p| p.id == id).unwrap();
        let (latte, mocha) = (find("catppuccin-latte"), find("catppuccin-mocha"));
        let css = render(&latte, Some(&mocha));
        assert!(css.starts_with(
            "/* Generated by Recoolor from catppuccin-latte and catppuccin-mocha */\n:root {\n"
        ));
        let (light, dark) = css
            .split_once("@media (prefers-color-scheme: dark) {\n")
            .unwrap();
        assert!(light.contains("  --ctp-base: #eff1f5 !important;\n"));
        assert!(dark.contains("  --ctp-base: #1e1e2e !important;\n"));
        assert!(dark.trim_end().ends_with("}\n}"));
    }

    #[test]
    fn apply_and_remove_leave_users_file_as_it_was() {
        let profile = tempfile::tempdir().unwrap();
        let user = "@import \"firefox-gnome-theme/userChrome.css\";\n";
        fs::create_dir_all(profile.path().join("chrome")).unwrap();
        fs::write(user_chrome(profile.path()), user).unwrap();
        let mocha = bundled()
            .into_iter()
            .find(|p| p.id == "catppuccin-mocha")
            .unwrap();

        apply(profile.path(), &mocha, None).unwrap();
        assert!(is_applied(profile.path()));
        assert!(render(&mocha, None).contains("  --ctp-base: #1e1e2e !important;\n"));
        assert!(!render(&mocha, None).contains("@media"));
        remove(profile.path()).unwrap();
        assert!(!css_path(profile.path()).exists());
        assert_eq!(
            fs::read_to_string(user_chrome(profile.path())).unwrap(),
            user
        );
    }
}
