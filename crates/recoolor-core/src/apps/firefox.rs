//! Firefox and Thunderbird: `chrome/recoolor.css` in each profile sets the color
//! variables that firefox-gnome-theme (`--gnome-*`), Catppuccin-style userChrome
//! files (`--ctp-*`) and Thunderbird's own chrome (`--layout-*`) read, and one
//! marked `@import` line in `userChrome.css` loads it after them. Both read
//! userChrome at startup, so they need a restart after Apply; both also need
//! `toolkit.legacyUserProfileCustomizations.stylesheets` turned on. With a
//! light/dark pair the dark colors sit in a `prefers-color-scheme` query, which
//! Firefox evaluates live, so a light/dark switch needs no restart.

use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::{ApplyError, io_err, read_or_empty, write_atomic};
use crate::palette::Palette;

const IMPORT: &str = "@import \"recoolor.css\"; /* Added by Recoolor; Reset removes it. */";
const CONTENT_IMPORT: &str =
    "@import \"recoolor-content.css\"; /* Added by Recoolor; Reset removes it. */";

/// Firefox's profile folders (`~/.mozilla/firefox`, `~/.config/mozilla/firefox`
/// used by newer releases, and Flathub's).
pub fn profiles(home: &Path) -> Vec<PathBuf> {
    profiles_in(&[
        home.join(".mozilla/firefox"),
        home.join(".config/mozilla/firefox"),
        home.join(".var/app/org.mozilla.firefox/.mozilla/firefox"),
    ])
}

/// Thunderbird's profile folders (the older `~/.thunderbird`, the XDG location
/// newer releases use, and Flathub's).
pub fn thunderbird_profiles(home: &Path) -> Vec<PathBuf> {
    profiles_in(&[
        home.join(".thunderbird"),
        home.join(".config/thunderbird"),
        home.join(".var/app/org.mozilla.Thunderbird/.thunderbird"),
    ])
}

/// Profile folders listed in each root's `profiles.ini`.
fn profiles_in(roots: &[PathBuf]) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for root in roots {
        let Ok(ini) = fs::read_to_string(root.join("profiles.ini")) else {
            continue;
        };
        for section in ini
            .split("\n[")
            .filter(|s| s.trim_start_matches('[').starts_with("Profile"))
        {
            let value = |key: &str| {
                section
                    .lines()
                    .find_map(|l| l.strip_prefix(key)?.strip_prefix('='))
                    .map(str::trim)
            };
            let Some(path) = value("Path") else { continue };
            let dir = if value("IsRelative") == Some("0") {
                PathBuf::from(path)
            } else {
                root.join(path)
            };
            if dir.is_dir() && !found.contains(&dir) {
                found.push(dir);
            }
        }
    }
    found
}

pub fn css_path(profile: &Path) -> PathBuf {
    profile.join("chrome/recoolor.css")
}

fn user_chrome(profile: &Path) -> PathBuf {
    profile.join("chrome/userChrome.css")
}

/// Firefox's own pages (Settings and other `about:` pages), through `userContent.css`.
fn content_path(profile: &Path) -> PathBuf {
    profile.join("chrome/recoolor-content.css")
}

fn user_content(profile: &Path) -> PathBuf {
    profile.join("chrome/userContent.css")
}

/// The palette for Firefox's own pages only (`about:`), never websites: the page,
/// card and text colors (the new tab is otherwise white or grey), the accent, and the
/// button hover and pressed colors, which Firefox's "Nova" design makes violet.
pub fn render_content(palette: &Palette, dark: Option<&Palette>) -> String {
    let rules = match dark {
        None => content_variables(palette),
        Some(dark) => format!(
            "{}@media (prefers-color-scheme: dark) {{\n{}}}\n",
            content_variables(palette),
            content_variables(dark)
        ),
    };
    format!(
        "/* Generated by Recoolor from {} */\n@-moz-document url-prefix(\"about:\") {{\n{rules}}}\n",
        palette.id
    )
}

fn content_variables(palette: &Palette) -> String {
    let (c, r) = (&palette.colors, crate::css::Roles::new(palette));
    let mut css = String::from(":root {\n");
    for (name, color) in [
        // Firefox's design tokens, which its pages draw from.
        ("--background-color-canvas", c.base),
        ("--background-color-box", r.card),
        ("--card-background-color", r.card),
        ("--text-color", c.text),
        ("--text-color-deemphasized", c.subtext),
        ("--color-accent-primary", c.accent),
        ("--button-background-color-hover", r.hover),
        ("--button-background-color-active", r.active),
        // The new tab's own, in case it sets them itself.
        ("--newtab-background-color", c.base),
        ("--newtab-background-color-secondary", r.card),
        ("--newtab-text-primary-color", c.text),
        // firefox-gnome-theme paints the new tab from these, on `body`, and defines
        // them again for pages (Adwaita's); without them the new tab stays white.
        ("--gnome-window-background", c.base),
        ("--gnome-window-color", c.text),
        ("--gnome-view-background", c.mantle),
        ("--gnome-menu-background", r.card),
        ("--gnome-card-background", r.card),
        ("--gnome-accent-bg", c.accent),
        ("--gnome-accent", c.accent),
    ] {
        let _ = writeln!(css, "  {name}: {color} !important;");
    }
    css.push_str("}\n");
    css
}

/// `palette`'s colors, or with `dark`, the light/dark pair: `palette` by
/// default and `dark` while the system (and so Firefox) is in dark style.
pub fn render(palette: &Palette, dark: Option<&Palette>) -> String {
    match dark {
        None => format!(
            "/* Generated by Recoolor from {} */\n{}",
            palette.id,
            variables(palette)
        ),
        Some(dark) => format!(
            "/* Generated by Recoolor from {} and {} */\n{}\n@media (prefers-color-scheme: dark) {{\n{}}}\n",
            palette.id,
            dark.id,
            variables(palette),
            variables(dark)
        ),
    }
}

