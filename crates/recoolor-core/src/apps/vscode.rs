//! VS Code: a local theme extension in `~/.vscode/extensions` contributing
//! "Recoolor Dark" and "Recoolor Light", and the one `workbench.colorTheme` line in the
//! user's `settings.json` that selects them.
//!
//! `settings.json` allows comments, so it is edited as text: only that key's value
//! changes (or one line is added), and everything else stays byte for byte.

use std::fs;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value, json};

use super::{ansi, is_ours, remove_owned, write_owned};
use crate::apply::{ApplyError, io_err, read_or_empty, write_atomic};
use crate::css::Roles;
use crate::palette::{Palette, Variant};

const KEY: &str = "\"workbench.colorTheme\"";

pub fn extension_dir(home: &Path) -> PathBuf {
    home.join(".vscode/extensions/recoolor.recoolor-theme-1.0.0")
}

pub fn settings_path(config_home: &Path) -> PathBuf {
    config_home.join("Code/User/settings.json")
}

/// The theme to select for a palette.
pub fn label(palette: &Palette) -> &'static str {
    match palette.variant {
        Variant::Dark => "Recoolor Dark",
        Variant::Light => "Recoolor Light",
    }
}

// The marker must sit in the first lines, where `is_ours` looks. `_watch` makes
// VS Code reload the theme file when Recoolor rewrites it, as it does for extensions
// under development.
const PACKAGE: &str = r#"{
  "description": "Generated by Recoolor from your current palette. Reset in Recoolor removes it.",
  "name": "recoolor-theme",
  "displayName": "Recoolor",
  "publisher": "recoolor",
  "version": "1.0.0",
  "engines": { "vscode": "^1.70.0" },
  "categories": ["Themes"],
  "contributes": {
    "themes": [
      { "label": "Recoolor Dark", "uiTheme": "vs-dark", "path": "./themes/dark.json", "_watch": true },
      { "label": "Recoolor Light", "uiTheme": "vs", "path": "./themes/light.json", "_watch": true }
    ]
  }
}
"#;

/// Writes the extension with `palette` as the theme for its variant. The other
/// variant's file keeps whatever it had, or gets the same palette the first time.
pub fn write_extension(home: &Path, palette: &Palette) -> Result<(), ApplyError> {
    let dir = extension_dir(home);
    write_owned(&dir.join("package.json"), PACKAGE)?;
    let theme = theme(palette);
    for (variant, file) in [(Variant::Dark, "dark.json"), (Variant::Light, "light.json")] {
        let path = dir.join("themes").join(file);
        if variant == palette.variant || !path.exists() {
            write_atomic(&path, &theme)?;
        }
    }
    Ok(())
}

/// Removes the extension if it is Recoolor's. Returns whether it was.
pub fn remove_extension(home: &Path) -> Result<bool, ApplyError> {
    let dir = extension_dir(home);
    if !remove_owned(&dir.join("package.json"))? {
        return Ok(false);
    }
    fs::remove_dir_all(&dir).map_err(io_err(&dir))?;
    Ok(true)
}

pub fn extension_installed(home: &Path) -> bool {
    is_ours(&extension_dir(home).join("package.json"))
}

