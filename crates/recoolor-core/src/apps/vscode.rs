    set("foreground", h(c.text));
    set("descriptionForeground", h(c.subtext));
    set("textLink.foreground", h(c.blue));
    set("editor.background", h(c.base));
    set("editor.foreground", h(c.text));
    set("editorCursor.foreground", h(c.accent));
    set("editor.selectionBackground", a(c.overlay, 0x66));
    set("editor.lineHighlightBackground", a(c.surface, 0x66));
    set("editorLineNumber.foreground", h(c.overlay));
    set("editorLineNumber.activeForeground", h(c.accent));
    set("editorIndentGuide.background", h(c.surface));
    set("editorWhitespace.foreground", h(c.surface));
    set("editorError.foreground", h(c.red));
    set("editorWarning.foreground", h(c.yellow));
    set("editorInfo.foreground", h(c.blue));
    set("editorWidget.background", h(c.mantle));
    set("editorGroupHeader.tabsBackground", h(c.mantle));
    set("tab.activeBackground", h(c.base));
    set("tab.inactiveBackground", h(c.mantle));
    set("tab.activeForeground", h(c.text));
    set("tab.inactiveForeground", h(c.overlay));
    set("tab.activeBorderTop", h(c.accent));
    set("tab.border", h(c.crust));
    set("sideBar.background", h(c.mantle));
    set("sideBar.foreground", h(c.text));
    set("sideBarSectionHeader.background", h(c.mantle));
    set("sideBarTitle.foreground", h(c.subtext));
    set("activityBar.background", h(c.crust));
    set("activityBar.foreground", h(c.accent));
    set("activityBar.inactiveForeground", h(c.overlay));
    set("activityBarBadge.background", h(c.accent));
    set("activityBarBadge.foreground", h(accent_fg));
    set("titleBar.activeBackground", h(c.crust));
    set("titleBar.activeForeground", h(c.text));
    set("titleBar.inactiveBackground", h(c.crust));
    set("titleBar.inactiveForeground", h(c.overlay));
    set("statusBar.background", h(c.crust));
    set("statusBar.foreground", h(c.subtext));
    set("statusBar.noFolderBackground", h(c.crust));
    set("statusBarItem.remoteBackground", h(c.accent));
    set("statusBarItem.remoteForeground", h(accent_fg));
    set("panel.background", h(c.base));
    set("panel.border", h(c.surface));
    set("panelTitle.activeBorder", h(c.accent));
    set("panelTitle.activeForeground", h(c.text));
    set("button.background", h(c.accent));
    set("button.foreground", h(accent_fg));
    set("button.secondaryBackground", h(c.surface));
    set("button.secondaryForeground", h(c.text));
    set("badge.background", h(c.accent));
    set("badge.foreground", h(accent_fg));
    set("input.background", h(c.mantle));
    set("input.foreground", h(c.text));
    set("input.border", h(c.surface));
    set("input.placeholderForeground", h(c.overlay));
