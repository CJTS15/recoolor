/// The flavor's `tmtheme.xml`, the syntax colors of code previews.
pub fn render_tmtheme(palette: &Palette) -> String {
    let c = &palette.colors;
    let mut scopes = String::new();
    for (scope, color) in [
        ("comment", c.overlay),
        ("string", c.green),
        (
            "constant.numeric, constant.language, constant.character",
            c.orange,
        ),
        ("keyword, storage", c.purple),
        ("entity.name.function, support.function", c.blue),
        ("entity.name.type, support.type, support.class", c.yellow),
        ("variable.parameter", c.pink),
        ("punctuation, keyword.operator", c.subtext),
        ("invalid", c.red),
    ] {
        let _ = writeln!(
            scopes,
            "      <dict><key>scope</key><string>{scope}</string><key>settings</key>\
             <dict><key>foreground</key><string>{color}</string></dict></dict>"
        );
    }
    format!(
        "\
<?xml version=\"1.0\" encoding=\"UTF-8\"?>
<!-- Generated by Recoolor from {id}. Reset in Recoolor (or `recoolor restore`) removes it. -->
<plist version=\"1.0\">
  <dict>
    <key>name</key><string>Recoolor</string>
    <key>settings</key>
    <array>
      <dict><key>settings</key><dict>
        <key>background</key><string>{base}</string>
        <key>foreground</key><string>{text}</string>
        <key>caret</key><string>{accent}</string>
        <key>lineHighlight</key><string>{surface}</string>
        <key>selection</key><string>{surface}</string>
      </dict></dict>
{scopes}    </array>
  </dict>
</plist>
",
        id = palette.id,
        base = c.base,
        text = c.text,
        accent = c.accent,
        surface = c.surface,
    )
}

const THEME: &str = "\
# Generated by Recoolor. Reset in Recoolor (or `recoolor restore`) puts your own back
# from theme.toml.recoolor-backup.
[flavor]
light = \"recoolor-light\"
dark = \"recoolor-dark\"
";

/// Writes both flavors (`now` for both, or a pair's halves) and Recoolor's
/// `theme.toml`, moving the user's own aside first.
pub fn write(
    config_home: &Path,
    now: &Palette,
    pair: Option<(&Palette, &Palette)>,
) -> Result<(), ApplyError> {
    let (light, dark) = pair.unwrap_or((now, now));
    for (name, palette) in [(LIGHT, light), (DARK, dark)] {
        let dir = flavor_dir(config_home, name);
        write_owned(&dir.join("flavor.toml"), &render_flavor(palette))?;
        write_owned(&dir.join("tmtheme.xml"), &render_tmtheme(palette))?;
    }
    let theme = theme_path(config_home);
    if theme.exists() && !is_ours(&theme) {
        let backup = backup_path(config_home);
        // Never over a backup already there: it may be the only copy of the user's.
        if backup.exists() {
            return Err(ApplyError::Foreign { path: theme });
        }
        fs::rename(&theme, &backup).map_err(io_err(&theme))?;
    }
    write_owned(&theme, THEME)
}

/// Removes Recoolor's files and puts the user's `theme.toml` back. True if there was
/// anything of Recoolor's.
pub fn remove(config_home: &Path) -> Result<bool, ApplyError> {
    let mut any = false;
    for name in [LIGHT, DARK] {
        let dir = flavor_dir(config_home, name);
        any |= remove_owned(&dir.join("flavor.toml"))?;
        any |= remove_owned(&dir.join("tmtheme.xml"))?;
        // Only when empty, which is exactly what is wanted.
        let _ = fs::remove_dir(&dir);
    }
    let theme = theme_path(config_home);
    any |= remove_owned(&theme)?;
    let backup = backup_path(config_home);
    if backup.exists() && !theme.exists() {
        fs::rename(&backup, &theme).map_err(io_err(&backup))?;
    }
    Ok(any)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn moves_the_users_theme_aside_and_back() {
        let p = |id: &str| bundled().into_iter().find(|p| p.id == id).unwrap();
        let (latte, mocha) = (p("catppuccin-latte"), p("catppuccin-mocha"));
        let home = tempfile::tempdir().unwrap();
        let theme = theme_path(home.path());
        fs::create_dir_all(theme.parent().unwrap()).unwrap();
        fs::write(&theme, "[mgr]\ncwd = { fg = \"#123456\" }\n").unwrap();

        write(home.path(), &mocha, Some((&latte, &mocha))).unwrap();
        assert!(
            fs::read_to_string(&theme)
                .unwrap()
                .contains("light = \"recoolor-light\"")
        );
        let dark = fs::read_to_string(flavor_dir(home.path(), DARK).join("flavor.toml")).unwrap();
        assert!(dark.contains("cwd = { fg = \"#94e2d5\" }"));
        assert!(dark.contains("{ url = \"*/\", fg = \"#89b4fa\" }"));
        let light = fs::read_to_string(flavor_dir(home.path(), LIGHT).join("tmtheme.xml")).unwrap();
        assert!(light.contains("<string>#eff1f5</string>"));
        // Again: the backup stays the user's own.
        write(home.path(), &mocha, None).unwrap();
        assert_eq!(
            fs::read_to_string(backup_path(home.path())).unwrap(),
            "[mgr]\ncwd = { fg = \"#123456\" }\n"
        );

        assert!(remove(home.path()).unwrap());
        assert_eq!(
            fs::read_to_string(&theme).unwrap(),
            "[mgr]\ncwd = { fg = \"#123456\" }\n"
        );
        assert!(!flavor_dir(home.path(), DARK).exists());
        assert!(!backup_path(home.path()).exists());
    }
}
