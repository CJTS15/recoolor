//! The fish shell: a `Recoolor` theme in `$XDG_CONFIG_HOME/fish/themes/Recoolor.theme`,
//! chosen by `conf.d/recoolor.fish`. A light/dark pair gives the theme a `[light]` and a
//! `[dark]` section, which fish switches with the terminal's background. fish reads
//! `conf.d` in name order, so this comes after its own `fish_frozen_theme.fish` and
//! wins. The same file keeps `RECOOLOR_COLOR_THEME` in step with fish's light/dark, for
//! oh-my-posh (see `ohmyposh`). New shells pick it up.

use std::fmt::Write;
use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::ApplyError;
use crate::palette::Palette;

/// The theme's name, as `fish_config theme choose` takes it.
pub const THEME: &str = "Recoolor";

/// `conf.d/recoolor.fish`, which selects the theme.
pub fn path(config_home: &Path) -> PathBuf {
    config_home.join("fish/conf.d/recoolor.fish")
}

pub fn theme_path(config_home: &Path) -> PathBuf {
    config_home
        .join("fish/themes")
        .join(format!("{THEME}.theme"))
}

/// The theme's variables for one palette, as fish's theme files write them.
fn colors(text: &mut String, palette: &Palette) {
    let c = &palette.colors;
    // fish takes colors as bare hex.
    let hex = |color: crate::color::Color| color.to_string()[1..].to_owned();
    let vars = [
        ("fish_color_normal", hex(c.text)),
        ("fish_color_command", hex(c.blue)),
        ("fish_color_param", hex(c.subtext)),
        ("fish_color_keyword", hex(c.purple)),
        ("fish_color_quote", hex(c.green)),
        ("fish_color_redirection", hex(c.pink)),
        ("fish_color_end", hex(c.orange)),
        ("fish_color_comment", hex(c.overlay)),
        ("fish_color_error", hex(c.red)),
        ("fish_color_gray", hex(c.overlay)),
        (
            "fish_color_selection",
            format!("--background={}", hex(c.surface)),
        ),
        (
            "fish_color_search_match",
            format!("--background={}", hex(c.surface)),
        ),
        ("fish_color_option", hex(c.teal)),
        ("fish_color_operator", hex(c.pink)),
        ("fish_color_escape", hex(c.red)),
        ("fish_color_autosuggestion", hex(c.overlay)),
        ("fish_color_cancel", hex(c.red)),
        ("fish_color_cwd", hex(c.yellow)),
        ("fish_color_user", hex(c.teal)),
        ("fish_color_host", hex(c.blue)),
        ("fish_color_host_remote", hex(c.green)),
        ("fish_color_status", hex(c.red)),
        ("fish_color_valid_path", "--underline".to_owned()),
        ("fish_pager_color_progress", hex(c.overlay)),
        ("fish_pager_color_prefix", hex(c.accent)),
        ("fish_pager_color_completion", hex(c.text)),
        ("fish_pager_color_description", hex(c.overlay)),
    ];
    for (name, value) in vars {
        let _ = writeln!(text, "{name} {value}");
    }
}

/// `Recoolor.theme`: `now` alone, or a pair's light and dark sections.
pub fn render_theme(now: &Palette, pair: Option<(&Palette, &Palette)>) -> String {
    let mut text = format!(
        "# Generated by Recoolor from {}. Reset in Recoolor (or `recoolor restore`) removes it.\n\
         # name: {THEME}\n",
        now.id
    );
    match pair {
        None => colors(&mut text, now),
        Some((light, dark)) => {
            text.push_str("\n[light]\n");
            colors(&mut text, light);
            text.push_str("\n[dark]\n");
            colors(&mut text, dark);
        }
    }
    text
}

/// The universal variable Recoolor sets on every change (the style, then a count):
/// fish shares it with every open shell, whose handler then takes the new colors.
pub const RELOAD: &str = "__recoolor_reload";

/// `conf.d/recoolor.fish`. With oh-my-posh, `omp` is Recoolor's config, which open
/// shells load again on a change (oh-my-posh caches its config per shell).
pub fn conf(omp: Option<&Path>) -> String {
    let omp = omp.map_or(String::new(), |path| {
        let quoted = path
            .display()
            .to_string()
            .replace('\\', "\\\\")
            .replace('\'', "\\'");
        format!("    oh-my-posh init fish --config '{quoted}' | source\n")
    });
    format!(
        "\
# Generated by Recoolor. Reset in Recoolor (or `recoolor restore`) removes it.
status is-interactive; or return
# The theme's light or dark half: the style Recoolor last set, else what the terminal
# reports. oh-my-posh takes its palette from RECOOLOR_COLOR_THEME the same way.
function __recoolor_theme
    set -l style (string split ' ' -- ${RELOAD})[1]
    if test -n \"$style\"
        fish_config theme choose {THEME} --color-theme=$style
        set --global --export RECOOLOR_COLOR_THEME $style
    else
        fish_config theme choose {THEME}
        set --global --export RECOOLOR_COLOR_THEME $fish_terminal_color_theme
    end
end
# Recoolor changes {RELOAD} on every change, so open shells recolor at once.
function __recoolor_reload --on-variable {RELOAD}
    set -q {RELOAD}[1]; or return
    __recoolor_theme
{omp}    commandline -f repaint
end
__recoolor_theme
"
    )
}

pub fn write(
    config_home: &Path,
    now: &Palette,
    pair: Option<(&Palette, &Palette)>,
    omp: Option<&Path>,
) -> Result<(), ApplyError> {
    write_owned(&theme_path(config_home), &render_theme(now, pair))?;
    write_owned(&path(config_home), &conf(omp))
}

/// Removes both files; true if there was either.
pub fn remove(config_home: &Path) -> Result<bool, ApplyError> {
    let theme = remove_owned(&theme_path(config_home))?;
    Ok(remove_owned(&path(config_home))? || theme)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn a_theme_with_both_halves_for_a_pair() {
        let p = |id: &str| bundled().into_iter().find(|p| p.id == id).unwrap();
        let (latte, mocha) = (p("catppuccin-latte"), p("catppuccin-mocha"));

        let single = render_theme(&mocha, None);
        assert!(single.starts_with("# Generated by Recoolor from catppuccin-mocha."));
        assert!(single.contains("# name: Recoolor\n"));
        assert!(single.contains("\nfish_color_command 89b4fa\n"));
        assert!(single.contains("\nfish_color_selection --background=313244\n"));
        assert!(!single.contains("[dark]"));

        let pair = render_theme(&mocha, Some((&latte, &mocha)));
        let (light, dark) = pair.split_once("\n[dark]\n").unwrap();
        assert!(light.contains("\n[light]\nfish_color_normal 4c4f69\n"));
        assert!(dark.starts_with("fish_color_normal cdd6f4\n"));

        let plain = conf(None);
        assert!(plain.contains("fish_config theme choose Recoolor --color-theme=$style\n"));
        assert!(plain.contains("function __recoolor_reload --on-variable __recoolor_reload\n"));
        assert!(!plain.contains("oh-my-posh init"));
        let omp = conf(Some(Path::new(
            "/home/me/.config/ohmyposh/recoolor.omp.json",
        )));
        assert!(omp.contains(
            "    oh-my-posh init fish --config '/home/me/.config/ohmyposh/recoolor.omp.json' | source\n"
        ));
    }
}
