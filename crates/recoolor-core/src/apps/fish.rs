//! The fish shell: `$XDG_CONFIG_HOME/fish/conf.d/recoolor.fish` sets the syntax colors
//! as globals. fish reads `conf.d` in name order, so this comes after its own
//! `fish_frozen_theme.fish` and wins; deleting it brings the user's colors back.
//! New shells pick it up.

use std::fmt::Write;
use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::ApplyError;
use crate::palette::Palette;

pub fn path(config_home: &Path) -> PathBuf {
    config_home.join("fish/conf.d/recoolor.fish")
}

/// `available` is what `fish_config theme list` prints, read once when applying.
pub fn render(palette: &Palette, available: &[String]) -> String {
    let c = &palette.colors;
    // fish takes colors as bare hex.
    let hex = |color: crate::color::Color| color.to_string()[1..].to_owned();
    let vars = [
        ("fish_color_normal", hex(c.text)),
        ("fish_color_command", hex(c.blue)),
        ("fish_color_param", hex(c.subtext)),
        ("fish_color_keyword", hex(c.purple)),
        ("fish_color_quote", hex(c.green)),
        ("fish_color_redirection", hex(c.pink)),
        ("fish_color_end", hex(c.orange)),
        ("fish_color_comment", hex(c.overlay)),
        ("fish_color_error", hex(c.red)),
        ("fish_color_gray", hex(c.overlay)),
        (
            "fish_color_selection",
            format!("--background={}", hex(c.surface)),
        ),
        (
            "fish_color_search_match",
            format!("--background={}", hex(c.surface)),
        ),
        ("fish_color_option", hex(c.teal)),
        ("fish_color_operator", hex(c.pink)),
        ("fish_color_escape", hex(c.red)),
        ("fish_color_autosuggestion", hex(c.overlay)),
        ("fish_color_cancel", hex(c.red)),
        ("fish_color_cwd", hex(c.yellow)),
        ("fish_color_user", hex(c.teal)),
        ("fish_color_host", hex(c.blue)),
        ("fish_color_host_remote", hex(c.green)),
        ("fish_color_status", hex(c.red)),
        ("fish_color_valid_path", "--underline".to_owned()),
        ("fish_pager_color_progress", hex(c.overlay)),
        ("fish_pager_color_prefix", hex(c.accent)),
        ("fish_pager_color_completion", hex(c.text)),
        ("fish_pager_color_description", hex(c.overlay)),
    ];
    let mut text = format!(
        "# Generated by Recoolor from {}. Reset in Recoolor (or `recoolor restore`) removes it.\n\
         status is-interactive; or return\n",
        palette.id
    );
    // The theme's own fish theme (the user's, then fish's built-in) matches upstream
    // exactly, so it wins over the generated colors when fish has it.
    if let Some(theme) = palette.apps.fish.iter().find(|t| available.contains(t)) {
        let quoted = theme.replace('\\', "\\\\").replace('\'', "\\'");
        let _ = writeln!(text, "fish_config theme choose '{quoted}'");
        return text;
    }
    for (name, value) in vars {
        let _ = writeln!(text, "set --global {name} {value}");
    }
    text
}

pub fn write(config_home: &Path, contents: &str) -> Result<(), ApplyError> {
    write_owned(&path(config_home), contents)
}

pub fn remove(config_home: &Path) -> Result<bool, ApplyError> {
    remove_owned(&path(config_home))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn prefers_an_installed_fish_theme() {
        let p = |id: &str| bundled().into_iter().find(|p| p.id == id).unwrap();
        let mocha = p("catppuccin-mocha");
        let installed = vec!["catppuccin-mocha".to_owned(), "nord".to_owned()];
        let text = render(&mocha, &installed);
        assert!(text.ends_with(
            "status is-interactive; or return\nfish_config theme choose 'catppuccin-mocha'\n"
        ));

        // Nothing installed: generated colors, as bare hex.
        let text = render(&mocha, &[]);
        assert!(text.contains("set --global fish_color_command 89b4fa\n"));
        assert!(text.contains("set --global fish_color_selection --background=313244\n"));
        assert!(text.lines().skip(1).all(|l| !l.contains('#')));
    }
}
