//! GtkSourceView 5 style schemes, used by GNOME Text Editor (and Builder):
//! `recoolor` (light) and `recoolor-dark` in
//! `$XDG_DATA_HOME/gtksourceview-5/styles/`, linked through their `variant`
//! metadata so the app switches between them with GNOME's style. Selecting the
//! scheme is the app's job.

use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::ApplyError;
use crate::palette::Palette;

/// The scheme to select; the app picks the dark variant by itself.
pub const SCHEME: &str = "recoolor";
const DARK: &str = "recoolor-dark";

pub fn path(data_home: &Path, id: &str) -> PathBuf {
    data_home
        .join("gtksourceview-5/styles")
        .join(format!("{id}.xml"))
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// One scheme. `dark` says which of the two it is.
pub fn render(palette: &Palette, dark: bool) -> String {
    let c = &palette.colors;
    let (id, variant, other_key, other) = if dark {
        (DARK, "dark", "light-variant", SCHEME)
    } else {
        (SCHEME, "light", "dark-variant", DARK)
    };
    let style = |name: &str, attrs: String| format!("  <style name=\"{name}\" {attrs}/>\n");
    let fg = |color: crate::color::Color| format!("foreground=\"{color}\"");
    let mut styles = String::new();
    for (name, attrs) in [
        (
            "text",
            format!("foreground=\"{}\" background=\"{}\"", c.text, c.base),
        ),
        (
            "selection",
            format!("background=\"{}\"", c.surface.mix(c.accent, 0.35)),
        ),
        ("cursor", fg(c.accent)),
        ("current-line", format!("background=\"{}\"", c.mantle)),
        (
            "line-numbers",
            format!("foreground=\"{}\" background=\"{}\"", c.overlay, c.base),
        ),
        (
            "current-line-number",
            format!("foreground=\"{}\" background=\"{}\"", c.text, c.mantle),
        ),
        ("background-pattern", format!("background=\"{}\"", c.mantle)),
        (
            "right-margin",
            format!("foreground=\"{}\" background=\"{}\"", c.surface, c.surface),
        ),
        ("draw-spaces", fg(c.surface)),
        ("map-overlay", format!("background=\"{}\"", c.overlay)),
        ("bracket-match", format!("{} bold=\"true\"", fg(c.accent))),
        (
            "search-match",
            format!("foreground=\"{}\" background=\"{}\"", c.base, c.yellow),
        ),
        ("def:comment", format!("{} italic=\"true\"", fg(c.overlay))),
        ("def:doc-comment-element", fg(c.subtext)),
        ("def:string", fg(c.green)),
        ("def:special-char", fg(c.pink)),
        ("def:keyword", format!("{} bold=\"true\"", fg(c.purple))),
        ("def:statement", format!("{} bold=\"true\"", fg(c.purple))),
        ("def:type", format!("{} bold=\"true\"", fg(c.yellow))),
        ("def:function", fg(c.blue)),
        ("def:identifier", fg(c.text)),
        ("def:constant", fg(c.orange)),
        ("def:number", fg(c.orange)),
        ("def:boolean", fg(c.orange)),
        ("def:preprocessor", fg(c.teal)),
        ("def:heading", format!("{} bold=\"true\"", fg(c.accent))),
        ("def:link-text", fg(c.blue)),
        (
            "def:net-address",
            format!("{} underline=\"low\"", fg(c.blue)),
        ),
        ("def:emphasis", "italic=\"true\"".to_owned()),
        ("def:strong-emphasis", "bold=\"true\"".to_owned()),
        ("def:underlined", "underline=\"single\"".to_owned()),
        (
            "def:error",
            format!("underline=\"error\" underline-color=\"{}\"", c.red),
        ),
        (
            "def:warning",
            format!("underline=\"error\" underline-color=\"{}\"", c.yellow),
        ),
        (
            "def:note",
            format!(
                "foreground=\"{}\" background=\"{}\" bold=\"true\"",
                c.base, c.yellow
            ),
        ),
        ("diff:added-line", fg(c.green)),
        ("diff:removed-line", fg(c.red)),
        ("diff:changed-line", fg(c.orange)),
    ] {
        styles.push_str(&style(name, attrs));
    }
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!-- Generated by Recoolor from {}. Reset in Recoolor removes it. -->\n\
         <style-scheme id=\"{id}\" name=\"Recoolor ({})\" version=\"1.0\">\n\
         <author>Recoolor</author>\n\
         <description>Generated from the {} palette</description>\n\
         <metadata>\n\
           <property name=\"variant\">{variant}</property>\n\
           <property name=\"{other_key}\">{other}</property>\n\
         </metadata>\n\
         {styles}</style-scheme>\n",
        palette.id,
        xml_escape(&palette.name),
        xml_escape(&palette.name),
    )
}

/// Writes both schemes: the light one from `light`, the dark one from `dark`.
pub fn write(data_home: &Path, light: &Palette, dark: &Palette) -> Result<(), ApplyError> {
    write_owned(&path(data_home, SCHEME), &render(light, false))?;
    write_owned(&path(data_home, DARK), &render(dark, true))
}

pub fn remove(data_home: &Path) -> Result<(), ApplyError> {
    remove_owned(&path(data_home, SCHEME))?;
    remove_owned(&path(data_home, DARK)).map(drop)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn schemes_link_their_variants_and_escape_names() {
        let p = |id: &str| bundled().into_iter().find(|p| p.id == id).unwrap();
        let mut latte = p("catppuccin-latte");
        latte.name = "Latte & <Co>".into();
        let light = render(&latte, false);
        assert!(light.contains("id=\"recoolor\" name=\"Recoolor (Latte &amp; &lt;Co&gt;)\""));
        assert!(light.contains("<property name=\"dark-variant\">recoolor-dark</property>"));
        assert!(
            light.contains("<style name=\"text\" foreground=\"#4c4f69\" background=\"#eff1f5\"/>")
        );
        let dark = render(&p("catppuccin-mocha"), true);
        assert!(dark.contains("<property name=\"light-variant\">recoolor</property>"));

        let home = tempfile::tempdir().unwrap();
        write(home.path(), &latte, &p("catppuccin-mocha")).unwrap();
        assert!(path(home.path(), "recoolor-dark").exists());
        remove(home.path()).unwrap();
        assert!(!path(home.path(), "recoolor").exists());
    }
}
