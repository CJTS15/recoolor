//! A small GNOME Shell extension for what Recoolor cannot do from outside the Shell:
//!
//! - Screen Fade: crossfades the screen while Recoolor applies a palette, the way the
//!   Shell does when Dark Style is toggled (the Shell's own transition is only
//!   callable by a few system components). Over D-Bus
//!   (`io.github.cjts15.Recoolor.Shell`): `Freeze` covers the screen with a still of
//!   itself; `Fade` fades that still away, by itself after five seconds at most.
//! - Lock screen image: GNOME draws the lock screen from the desktop wallpaper and
//!   has no setting of its own, so the extension replaces
//!   `UnlockDialog._createBackground` (a private method; recheck after GNOME
//!   upgrades, tested on GNOME Shell 50) to draw Recoolor's image instead.
//!
//! The extension reads its choices from [`config_path`] each time the screen locks.

use std::fs;
use std::path::{Path, PathBuf};

use super::{is_ours, remove_owned, write_owned};
use crate::apply::{ApplyError, io_err};

pub const UUID: &str = "recoolor@cjts15.github.io";
pub const BUS_NAME: &str = "io.github.cjts15.Recoolor.Shell";
pub const OBJECT_PATH: &str = "/io/github/cjts15/Recoolor/Shell";

// The marker sits on the first lines, where `is_ours` looks.
const METADATA: &str = r#"{
  "description": "Generated by Recoolor: screen fade and lock screen image for Recoolor. Reset in Recoolor removes it.",
  "uuid": "recoolor@cjts15.github.io",
  "name": "Recoolor",
  "session-modes": ["user", "unlock-dialog"],
  "shell-version": ["47", "48", "49", "50"],
  "url": "https://github.com/CJTS15/recoolor"
}
"#;

const EXTENSION: &str = r#"// Generated by Recoolor. Reset in Recoolor removes it.
import Clutter from 'gi://Clutter';
import GDesktopEnums from 'gi://GDesktopEnums';
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import Meta from 'gi://Meta';
import Mtk from 'gi://Mtk';
import Shell from 'gi://Shell';
import St from 'gi://St';

import * as Main from 'resource:///org/gnome/shell/ui/main.js';
import * as UnlockDialog from 'resource:///org/gnome/shell/ui/unlockDialog.js';
import {Extension} from 'resource:///org/gnome/shell/extensions/extension.js';

const IFACE = `<node>
  <interface name="io.github.cjts15.Recoolor.Shell">
    <method name="Freeze"/>
    <method name="Fade"/>
    <method name="ReloadTheme"/>
  </interface>
</node>`;

// Close to GNOME's own Dark Style transition (250 ms, then 500 ms).
const FADE_MS = 500;
// Lets apps finish redrawing under the still before it fades.
const SETTLE_MS = 100;
const MAX_FREEZE_MS = 3000;

function config() {
    const file = GLib.build_filenamev([GLib.get_user_data_dir(), 'recoolor', 'shell-extension.conf']);
    const keyFile = new GLib.KeyFile();
    try {
        keyFile.load_from_file(file, GLib.KeyFileFlags.NONE);
    } catch {}
    return keyFile;
}

function fadeEnabled() {
    try {
        return config().get_boolean('Screen Fade', 'enabled');
    } catch {
        return false;
    }
}

// Blur my Shell's popup settings, from the schema it ships; null without it.
function blurMyShellPopupSettings() {
    const bms = Main.extensionManager.lookup('blur-my-shell@aunetx');
    const dir = bms?.dir.get_child('schemas');
    if (!dir?.query_exists(null))
        return null;
    try {
        const source = Gio.SettingsSchemaSource.new_from_directory(
            dir.get_path(), Gio.SettingsSchemaSource.get_default(), false);
        const schema = source.lookup('org.gnome.shell.extensions.blur-my-shell.popup', true);
        return schema ? new Gio.Settings({settings_schema: schema}) : null;
    } catch {
        return null;
    }
}

// Recoolor's lock screen choice: {image, blur}, or no image.
function lockScreen() {
    const keyFile = config();
    try {
        const image = keyFile.get_string('Lock Screen', 'image');
        let blur = true;
        try {
            blur = keyFile.get_boolean('Lock Screen', 'blur');
        } catch {}
        return GLib.file_test(image, GLib.FileTest.EXISTS) ? {image, blur} : {};
    } catch {
        return {};
    }
}

// The Shell's own _createBackground, with Recoolor's image in place of the
// desktop's when one is set. `this` is the UnlockDialog.
function createBackground(original, monitorIndex) {
    const {image, blur} = lockScreen();
    if (!image)
        return original.call(this, monitorIndex);
    const monitor = Main.layoutManager.monitors[monitorIndex];
    // Without the effect the Shell's blur settings have nothing to apply to.
    const widget = new St.Widget({
        style_class: 'screen-shield-background',
        x: monitor.x,
        y: monitor.y,
        width: monitor.width,
        height: monitor.height,
        effect: blur ? new Shell.BlurEffect({name: 'blur'}) : null,
    });
    const background = new Meta.Background({meta_display: global.display});
    background.set_file(Gio.File.new_for_path(image), GDesktopEnums.BackgroundStyle.ZOOM);
    const actor = new Meta.BackgroundActor({
        meta_display: global.display,
        monitor: monitorIndex,
        x_expand: true,
        y_expand: true,
    });
    actor.content.set({background});
    widget.add_child(actor);
    // The dialog destroys its managers before rebuilding; the widget goes with the group.
    this._bgManagers.push({destroy() {}});
    this._backgroundGroup.add_child(widget);
}

export default class Recoolor extends Extension {
    enable() {
        const proto = UnlockDialog.UnlockDialog.prototype;
        const original = proto._createBackground;
        this._originalCreateBackground = original;
        proto._createBackground = function (monitorIndex) {
            return createBackground.call(this, original, monitorIndex);
        };

        this._cover = new Clutter.Actor({visible: false});
        Main.uiGroup.add_child(this._cover);
        this._timeout = 0;
        this._dbus = Gio.DBusExportedObject.wrapJSObject(IFACE, this);
        this._dbus.export(Gio.DBus.session, '/io/github/cjts15/Recoolor/Shell');
        this._name = Gio.bus_own_name_on_connection(Gio.DBus.session,
            'io.github.cjts15.Recoolor.Shell', Gio.BusNameOwnerFlags.NONE, null, null);

        // A light/dark or accent switch: hold a still of the old look while
        // Recoolor's watcher restyles everything; it calls Fade when done.
        this._interface = new Gio.Settings({schema_id: 'org.gnome.desktop.interface'});
        const keys = ['color-scheme', 'accent-color'];
        this._seen = Object.fromEntries(keys.map(k => [k, this._interface.get_string(k)]));
        this._interfaceChanged = this._interface.connect('changed', (settings, key) => {
            // GSettings also reports keys whose value did not change.
            if (!keys.includes(key) || settings.get_string(key) === this._seen[key])
                return;
            this._seen[key] = settings.get_string(key);
            if (fadeEnabled())
                this.Freeze();
        });

        // Blur my Shell's popups: see-through over its blur, solid while that blur
        // is off (Recoolor's stylesheet keys its solid colors to this class).
        // Extensions start in no set order, so also when Blur my Shell loads.
        this._extensionState = Main.extensionManager.connect('extension-state-changed',
            (_manager, extension) => {
                if (extension.uuid === 'blur-my-shell@aunetx')
                    this._watchBlurMyShell();
            });
        this._watchBlurMyShell();

        // High Contrast: Recoolor's theme loads over GNOME's high-contrast one, so
        // Recoolor's stylesheet redraws its outlines and focus rings under this class.
        this._highContrastChanged = St.Settings.get().connect('notify::high-contrast',
            () => this._syncHighContrast());
        this._syncHighContrast();
    }

    _syncHighContrast() {
        if (St.Settings.get().high_contrast)
            Main.uiGroup.add_style_class_name('recoolor-high-contrast');
        else
            Main.uiGroup.remove_style_class_name('recoolor-high-contrast');
    }

    _watchBlurMyShell() {
        if (this._bmsChanged)
            this._bmsPopup.disconnect(this._bmsChanged);
        this._bmsPopup = blurMyShellPopupSettings();
        this._bmsChanged = this._bmsPopup?.connect('changed::blur', () => this._syncSolidPopups());
        this._syncSolidPopups();
    }

    _syncSolidPopups() {
        if (this._bmsPopup && !this._bmsPopup.get_boolean('blur'))
            Main.uiGroup.add_style_class_name('recoolor-solid-popups');
        else
            Main.uiGroup.remove_style_class_name('recoolor-solid-popups');
    }

    disable() {
        this._interface.disconnect(this._interfaceChanged);
        this._interface = null;
        Main.extensionManager.disconnect(this._extensionState);
        if (this._bmsChanged)
            this._bmsPopup.disconnect(this._bmsChanged);
        this._bmsChanged = 0;
        this._bmsPopup = null;
        Main.uiGroup.remove_style_class_name('recoolor-solid-popups');
        St.Settings.get().disconnect(this._highContrastChanged);
        Main.uiGroup.remove_style_class_name('recoolor-high-contrast');
        UnlockDialog.UnlockDialog.prototype._createBackground = this._originalCreateBackground;
        Gio.bus_unown_name(this._name);
        this._dbus.unexport();
        this._dbus = null;
        if (this._timeout)
            GLib.source_remove(this._timeout);
        this._timeout = 0;
        this._cover.destroy();
        this._cover = null;
    }

    // Covers the screen with a still of itself, as the Shell's ScreenTransition does.
    Freeze() {
        const cover = this._cover;
        // Already frozen; but a switch during the last fade freezes again, from what
        // is on screen now (the half-faded still included), so it does not jump.
        if (!cover || (cover.visible && !cover.get_transition('opacity')))
            return;
        const rect = new Mtk.Rectangle({
            x: 0, y: 0, width: global.screen_width, height: global.screen_height,
        });
        const [, , , scale] = global.stage.get_capture_final_size(rect);
        const still = global.stage.paint_to_content(rect, scale, null,
            Clutter.PaintFlag.NO_CURSORS);
        cover.remove_all_transitions();
        cover.content = still;
        cover.set_position(0, 0);
        cover.set_size(global.screen_width, global.screen_height);
        Main.uiGroup.set_child_above_sibling(cover, null);
        cover.opacity = 255;
        cover.show();
        if (this._timeout)
            GLib.source_remove(this._timeout);
        this._timeout = GLib.timeout_add(GLib.PRIORITY_DEFAULT, MAX_FREEZE_MS, () => {
            this._timeout = 0;
            this.Fade();
            return GLib.SOURCE_REMOVE;
        });
    }

    Fade() {
        if (this._timeout)
            GLib.source_remove(this._timeout);
        this._timeout = 0;
        const cover = this._cover;
        // Already fading: easing again would stop that fade, whose end hides the
        // cover at once (Apply and the watcher can both ask).
        if (!cover || !cover.visible || cover.get_transition('opacity'))
            return;
        cover.ease({
            opacity: 0,
            duration: FADE_MS,
            delay: SETTLE_MS,
            mode: Clutter.AnimationMode.EASE_IN_OUT_CUBIC,
            // Not when Freeze cut it short: the cover stays up for the next switch.
            onStopped: finished => {
                if (!finished)
                    return;
                cover.hide();
                cover.content = null;
            },
        });
    }

    // Loads the Shell theme again from its file: one load, where setting the
    // User Themes name away and back loads the default theme in between.
    ReloadTheme() {
        Main.loadTheme();
    }
}
"#;

/// The extension's settings, written by Recoolor and read by the extension.
pub fn config_path(data_home: &Path) -> PathBuf {
    data_home.join("recoolor/shell-extension.conf")
}

/// What the extension should do.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Config {
    /// Recoolor fades the screen around Apply.
    pub fade: bool,
    /// The (tinted) image to show on the lock screen.
    pub lock_image: Option<String>,
    pub lock_blur: bool,
    /// Blur my Shell's popups take the palette, from the extension's stylesheet.
    /// Not saved: Recoolor decides it on each Apply.
    pub popups: bool,
}

impl Config {
    /// Whether the extension has anything to do, so must be installed.
    pub fn wanted(&self) -> bool {
        self.fade || self.lock_image.is_some() || self.popups
    }
}

/// A GLib key file string value.
fn escape(value: &str) -> String {
    let escaped = value
        .replace('\\', "\\\\")
        .replace('\n', "\\n")
        .replace('\t', "\\t");
    match escaped.strip_prefix(' ') {
        Some(rest) => format!("\\s{rest}"),
        None => escaped,
    }
}

fn unescape(value: &str) -> String {
    let mut out = String::new();
    let mut chars = value.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('s') => out.push(' '),
            Some(other) => out.push(other),
            None => {}
        }
    }
    out
}

/// Writes the settings, or removes the file when there is nothing to do.
pub fn write_config(data_home: &Path, config: &Config) -> Result<(), ApplyError> {
    let path = config_path(data_home);
    if !config.wanted() {
        remove_owned(&path)?;
        return Ok(());
    }
    let mut text = format!(
        "# Generated by Recoolor. Reset in Recoolor removes it.\n[Screen Fade]\nenabled={}\n",
        config.fade
    );
    if let Some(image) = &config.lock_image {
        text.push_str(&format!(
            "\n[Lock Screen]\nimage={}\nblur={}\n",
            escape(image),
            config.lock_blur
        ));
    }
    write_owned(&path, &text)
}

/// The settings Recoolor last wrote; the defaults when there are none.
pub fn read_config(data_home: &Path) -> Config {
    let text = fs::read_to_string(config_path(data_home)).unwrap_or_default();
    let mut config = Config {
        lock_blur: true,
        ..Config::default()
    };
    for line in text.lines() {
        match line.split_once('=') {
            Some(("enabled", v)) => config.fade = v == "true",
            Some(("image", v)) => config.lock_image = Some(unescape(v)),
            Some(("blur", v)) => config.lock_blur = v == "true",
            _ => {}
        }
    }
    config
}

pub fn dir(data_home: &Path) -> PathBuf {
    data_home.join("gnome-shell/extensions").join(UUID)
}

const STYLESHEET: &str = "/* Generated by Recoolor. Reset in Recoolor removes it. */\n";

/// The Shell loads an extension's stylesheet only if it is there when the
/// extension starts, so `install` always leaves one.
pub fn stylesheet_path(data_home: &Path) -> PathBuf {
    dir(data_home).join("stylesheet.css")
}

pub fn install(data_home: &Path) -> Result<(), ApplyError> {
    let dir = dir(data_home);
    write_owned(&dir.join("metadata.json"), METADATA)?;
    write_owned(&dir.join("extension.js"), EXTENSION)?;
    if !stylesheet_path(data_home).exists() {
        write_owned(&stylesheet_path(data_home), STYLESHEET)?;
    }
    Ok(())
}

/// The extension's stylesheet: `css` under the marker. The Shell rereads it when
/// its theme reloads.
pub fn write_stylesheet(data_home: &Path, css: &str) -> Result<(), ApplyError> {
    write_owned(&stylesheet_path(data_home), &format!("{STYLESHEET}{css}\n"))
}

pub fn is_installed(data_home: &Path) -> bool {
    is_ours(&dir(data_home).join("metadata.json"))
}

/// Removes the extension if it is Recoolor's. Returns whether it was.
pub fn remove(data_home: &Path) -> Result<bool, ApplyError> {
    let dir = dir(data_home);
    if !remove_owned(&dir.join("metadata.json"))? {
        return Ok(false);
    }
    remove_owned(&dir.join("extension.js"))?;
    remove_owned(&stylesheet_path(data_home))?;
    // Only empty now unless someone added files; then it stays.
    match fs::remove_dir(&dir) {
        Err(e) if e.kind() != std::io::ErrorKind::DirectoryNotEmpty => Err(io_err(&dir)(e)),
        _ => Ok(true),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_round_trips_odd_paths_and_goes_when_unused() {
        let home = tempfile::tempdir().unwrap();
        let config = Config {
            fade: false,
            lock_image: Some(" /a b\\c\nd.png".into()),
            lock_blur: false,
            popups: false,
        };
        write_config(home.path(), &config).unwrap();
        let text = fs::read_to_string(config_path(home.path())).unwrap();
        assert!(text.contains("image=\\s/a b\\\\c\\nd.png\n"), "{text}");
        assert_eq!(read_config(home.path()), config);
        write_config(home.path(), &Config::default()).unwrap();
        assert!(!config_path(home.path()).exists());
        let defaults = Config {
            lock_blur: true,
            ..Config::default()
        };
        assert_eq!(read_config(home.path()), defaults);
    }

    #[test]
    fn install_and_remove() {
        let home = tempfile::tempdir().unwrap();
        install(home.path()).unwrap();
        assert!(is_installed(home.path()));
        let metadata: serde_json::Value = serde_json::from_str(
            &fs::read_to_string(dir(home.path()).join("metadata.json")).unwrap(),
        )
        .unwrap();
        assert_eq!(metadata["uuid"], UUID);
        write_stylesheet(home.path(), ".a { color: red; }").unwrap();
        assert!(is_ours(&stylesheet_path(home.path())));
        // A reinstall keeps the stylesheet written since.
        install(home.path()).unwrap();
        assert!(
            fs::read_to_string(stylesheet_path(home.path()))
                .unwrap()
                .contains(".a {")
        );
        assert!(remove(home.path()).unwrap());
        assert!(!dir(home.path()).exists());
        assert!(!remove(home.path()).unwrap());
    }
}
