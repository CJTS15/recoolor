//! Qt apps that use KDE's color schemes: KDE apps on the host, and Qt Flatpaks on
//! the KDE runtime (Kdenlive, Shotcut, …), which read `$XDG_CONFIG_HOME/kdeglobals`
//! (their Flatpak permissions grant it). Recoolor writes that file with a color
//! scheme from the palette, only when the user has no `kdeglobals` of their own.
//!
//! Host Qt apps that are not KDE apps use Qt's GTK3 platform theme on GNOME, which
//! takes its colors from GTK3, so they follow Recoolor's GTK3 colors already.

use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use crate::apply::{ApplyError, io_err, write_atomic};
use crate::color::Color;
use crate::css::Roles;
use crate::palette::Palette;

pub fn path(config_home: &Path) -> PathBuf {
    config_home.join("kdeglobals")
}

fn rgb(c: Color) -> String {
    format!("{},{},{}", c.r, c.g, c.b)
}

/// A KDE color scheme for `palette`.
pub fn render(palette: &Palette) -> String {
    let c = &palette.colors;
    let accent_fg = Roles::new(palette).accent_fg;
    let mut text = format!(
        "# Generated by Recoolor from {}. Reset in Recoolor removes it.\n\
         [General]\nColorScheme=Recoolor\nName=Recoolor\n",
        palette.id
    );
    // KDE's color sets, each with its own background and the shared foregrounds.
    let sets = [
        ("Window", c.base, c.mantle, c.text),
        ("View", c.mantle, c.base, c.text),
        ("Button", c.surface, c.surface.mix(c.overlay, 0.25), c.text),
        ("Selection", c.accent, c.accent.mix(c.base, 0.2), accent_fg),
        ("Tooltip", c.crust, c.mantle, c.text),
        ("Complementary", c.crust, c.mantle, c.text),
        ("Header", c.mantle, c.base, c.text),
    ];
    for (set, background, alternate, foreground) in sets {
        let _ = write!(
            text,
            "\n[Colors:{set}]\n\
             BackgroundNormal={}\nBackgroundAlternate={}\n\
             ForegroundNormal={}\nForegroundInactive={}\nForegroundActive={}\n\
             ForegroundLink={}\nForegroundVisited={}\n\
             ForegroundNegative={}\nForegroundNeutral={}\nForegroundPositive={}\n\
             DecorationFocus={}\nDecorationHover={}\n",
            rgb(background),
            rgb(alternate),
            rgb(foreground),
            rgb(c.subtext),
            rgb(c.accent),
            rgb(c.blue),
            rgb(c.purple),
            rgb(c.red),
            rgb(c.yellow),
            rgb(c.green),
            rgb(c.accent),
            rgb(c.accent),
        );
    }
    let _ = write!(
        text,
        "\n[WM]\nactiveBackground={}\nactiveForeground={}\n\
         inactiveBackground={}\ninactiveForeground={}\n",
        rgb(c.mantle),
        rgb(c.text),
        rgb(c.base),
        rgb(c.subtext),
    );
    text
}

/// Recoolor's by its marker comment, or by its scheme name: KDE's settings library
/// rewrites the whole file when a KDE app saves a setting, dropping comments.
pub fn is_applied(config_home: &Path) -> bool {
    let path = path(config_home);
    super::is_ours(&path)
        || fs::read_to_string(&path).is_ok_and(|t| t.lines().any(|l| l == "ColorScheme=Recoolor"))
}

pub fn write(config_home: &Path, palette: &Palette) -> Result<(), ApplyError> {
    let path = path(config_home);
    if path.exists() && !is_applied(config_home) {
        return Err(ApplyError::Foreign { path });
    }
    write_atomic(&path, &render(palette))
}

/// Removes the file if it is Recoolor's. Returns whether it was.
pub fn remove(config_home: &Path) -> Result<bool, ApplyError> {
    if !is_applied(config_home) {
        return Ok(false);
    }
    let path = path(config_home);
    fs::remove_file(&path).map_err(io_err(&path))?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;
    use crate::palette::bundled;

    #[test]
    fn scheme_sets_and_ownership() {
        let mocha = bundled()
            .into_iter()
            .find(|p| p.id == "catppuccin-mocha")
            .unwrap();
        let text = render(&mocha);
        assert!(text.contains("[Colors:Window]\nBackgroundNormal=30,30,46\n"));
        assert!(text.contains("[Colors:Selection]\nBackgroundNormal=203,166,247\n"));
        assert_eq!(text.matches("[Colors:").count(), 7);

        let home = tempfile::tempdir().unwrap();
        write(home.path(), &mocha).unwrap();
        assert!(is_applied(home.path()));
        assert!(remove(home.path()).unwrap());
        // Still Recoolor's after KDE rewrote it without the comment.
        fs::write(
            path(home.path()),
            "[General]\nColorScheme=Recoolor\n[KDE]\nSingleClick=false\n",
        )
        .unwrap();
        assert!(is_applied(home.path()));
        write(home.path(), &mocha).unwrap();
        assert!(remove(home.path()).unwrap());
        // The user's own kdeglobals is never replaced or removed.
        fs::write(path(home.path()), "[General]\nColorScheme=Breeze\n").unwrap();
        assert!(write(home.path(), &mocha).is_err());
        assert!(!remove(home.path()).unwrap());
    }
}
