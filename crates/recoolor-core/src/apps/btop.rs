//! btop++: a `recoolor.theme` in `$XDG_CONFIG_HOME/btop/themes/`, selected by the
//! `color_theme` line of `btop.conf`. btop reloads its config on SIGUSR2, so open
//! windows switch too.

use std::fmt::Write;
use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::{ApplyError, read_or_empty, write_atomic};
use crate::palette::Palette;

/// What `color_theme` holds when the line is missing.
pub const DEFAULT_THEME: &str = "Default";

pub fn theme_path(config_home: &Path) -> PathBuf {
    config_home.join("btop/themes/recoolor.theme")
}

pub fn conf_path(config_home: &Path) -> PathBuf {
    config_home.join("btop/btop.conf")
}

pub fn render(palette: &Palette) -> String {
    let c = &palette.colors;
    let keys = [
        ("main_bg", c.base),
        ("main_fg", c.text),
        ("title", c.text),
        ("hi_fg", c.accent),
        ("selected_bg", c.surface),
        ("selected_fg", c.accent),
        ("inactive_fg", c.overlay),
        ("graph_text", c.subtext),
        ("meter_bg", c.surface),
        ("proc_misc", c.teal),
        ("cpu_box", c.accent),
        ("mem_box", c.accent),
        ("net_box", c.accent),
        ("proc_box", c.accent),
        ("div_line", c.overlay),
        ("temp_start", c.green),
        ("temp_mid", c.yellow),
        ("temp_end", c.red),
        ("cpu_start", c.teal),
        ("cpu_mid", c.blue),
        ("cpu_end", c.purple),
        ("free_start", c.purple),
        ("free_mid", c.blue),
        ("free_end", c.teal),
        ("cached_start", c.teal),
        ("cached_mid", c.blue),
        ("cached_end", c.purple),
        ("available_start", c.orange),
        ("available_mid", c.pink),
        ("available_end", c.red),
        ("used_start", c.green),
        ("used_mid", c.teal),
        ("used_end", c.blue),
        ("download_start", c.orange),
        ("download_mid", c.pink),
        ("download_end", c.red),
        ("upload_start", c.green),
        ("upload_mid", c.teal),
        ("upload_end", c.blue),
        ("process_start", c.teal),
        ("process_mid", c.blue),
        ("process_end", c.purple),
    ];
    let mut text = format!(
        "# Generated by Recoolor from {}. Reset in Recoolor (or `recoolor restore`) removes it.\n",
        palette.id
    );
    for (key, color) in keys {
        let _ = writeln!(text, "theme[{key}]=\"{color}\"");
    }
    text
}

pub fn write_theme(config_home: &Path, contents: &str) -> Result<(), ApplyError> {
    write_owned(&theme_path(config_home), contents)
}

pub fn remove_theme(config_home: &Path) -> Result<bool, ApplyError> {
    remove_owned(&theme_path(config_home))
}

pub fn read_conf(path: &Path) -> Result<String, ApplyError> {
    read_or_empty(path)
}

pub fn write_conf(path: &Path, text: &str) -> Result<(), ApplyError> {
    write_atomic(path, text)
}

fn is_theme_line(line: &str) -> bool {
    line.trim_start()
        .strip_prefix("color_theme")
        .is_some_and(|rest| rest.trim_start().starts_with('='))
}

/// The `color_theme` value, unquoted.
pub fn current_theme(conf: &str) -> Option<String> {
    let line = conf.lines().find(|l| is_theme_line(l))?;
    let (_, value) = line.split_once('=')?;
    Some(value.trim().trim_matches('"').to_owned())
}

/// `conf` with `color_theme` set to `theme`, appended if the line is missing.
pub fn set_theme(conf: &str, theme: &str) -> String {
    let wanted = format!("color_theme = \"{theme}\"");
    let mut found = false;
    let mut text: String = conf
        .lines()
        .map(|l| {
            if is_theme_line(l) {
                found = true;
                wanted.as_str()
            } else {
                l
            }
        })
        .collect::<Vec<_>>()
        .join("\n");
    if !found {
        if !text.is_empty() {
            text.push('\n');
        }
        text.push_str(&wanted);
    }
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn renders_every_key_as_hex() {
        let mocha = bundled()
            .into_iter()
            .find(|p| p.id == "catppuccin-mocha")
            .unwrap();
        let text = render(&mocha);
        assert!(text.starts_with("# Generated by Recoolor from catppuccin-mocha."));
        assert!(text.contains("theme[main_bg]=\"#1e1e2e\"\n"));
        assert_eq!(text.lines().filter(|l| l.starts_with("theme[")).count(), 42);
    }

    #[test]
    fn edits_only_the_theme_line_and_puts_it_back() {
        let conf =
            "#* Name of a theme\ncolor_theme = \"/x/mine.theme\"\n\ntheme_background = true\n";
        assert_eq!(current_theme(conf).as_deref(), Some("/x/mine.theme"));
        let ours = set_theme(conf, "/c/btop/themes/recoolor.theme");
        assert_eq!(
            ours,
            "#* Name of a theme\ncolor_theme = \"/c/btop/themes/recoolor.theme\"\n\ntheme_background = true\n"
        );
        assert_eq!(set_theme(&ours, "/x/mine.theme"), conf);

        assert_eq!(current_theme("truecolor = true\n"), None);
        assert_eq!(
            set_theme("truecolor = true\n", "Default"),
            "truecolor = true\ncolor_theme = \"Default\"\n"
        );
        assert_eq!(set_theme("", "Default"), "color_theme = \"Default\"\n");
    }
}
