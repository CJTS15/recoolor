//! Ptyxis, GNOME's terminal: a `Recoolor` palette in
//! `$XDG_DATA_HOME/org.gnome.Ptyxis/palettes/`. A light/dark pair goes in the
//! file's `[Light]` and `[Dark]` sections, so Ptyxis switches by itself. Selecting
//! the palette in a profile is the app's job.

use std::fmt::Write;
use std::path::{Path, PathBuf};

use super::{ansi, remove_owned, write_owned};
use crate::apply::ApplyError;
use crate::palette::Palette;

/// The palette's id, which the profile's `palette` setting names.
pub const PALETTE_ID: &str = "Recoolor";

pub fn path(data_home: &Path) -> PathBuf {
    data_home
        .join("org.gnome.Ptyxis/palettes")
        .join(format!("{PALETTE_ID}.palette"))
}

/// Ptyxis's own palette (generated from Gogh) for what is on screen, if the
/// palette names one. A pair needs both halves to name the same one, since Ptyxis
/// switches a built-in palette's light and dark halves by itself.
// ponytail: a single light palette naming a two-sided built-in (Gruvbox,
// Everforest) shows the dark half while GNOME is dark; generate instead if that bites.
pub fn builtin<'a>(now: &'a Palette, pair: Option<(&'a Palette, &'a Palette)>) -> Option<&'a str> {
    match pair {
        None => now.apps.ptyxis.as_deref(),
        Some((light, dark)) => light
            .apps
            .ptyxis
            .as_deref()
            .filter(|name| dark.apps.ptyxis.as_deref() == Some(*name)),
    }
}

/// `now` fills the main section; a `pair` adds light and dark sections.
pub fn render(now: &Palette, pair: Option<(&Palette, &Palette)>) -> String {
    let mut text = format!(
        "# Generated by Recoolor from {}\n[Palette]\nName={PALETTE_ID}\n",
        now.id
    );
    colors(&mut text, now);
    if let Some((light, dark)) = pair {
        text.push_str("\n[Light]\n");
        colors(&mut text, light);
        text.push_str("\n[Dark]\n");
        colors(&mut text, dark);
    }
    text
}

fn colors(text: &mut String, palette: &Palette) {
    let c = &palette.colors;
    let _ = writeln!(text, "Background={}", c.base);
    let _ = writeln!(text, "Foreground={}", c.text);
    let _ = writeln!(text, "Cursor={}", c.accent);
    for (i, color) in ansi(palette).iter().enumerate() {
        let _ = writeln!(text, "Color{i}={color}");
    }
}

pub fn write(data_home: &Path, contents: &str) -> Result<(), ApplyError> {
    write_owned(&path(data_home), contents)
}

pub fn remove(data_home: &Path) -> Result<bool, ApplyError> {
    remove_owned(&path(data_home))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn single_and_pair_layouts() {
        let p = |id: &str| bundled().into_iter().find(|p| p.id == id).unwrap();
        let (latte, mocha) = (p("catppuccin-latte"), p("catppuccin-mocha"));

        let single = render(&mocha, None);
        assert!(single.starts_with(
            "# Generated by Recoolor from catppuccin-mocha\n[Palette]\nName=Recoolor\n"
        ));
        assert!(single.contains("Background=#1e1e2e\n"));
        assert!(single.contains("Color6=#94e2d5\n"));
        assert!(single.contains("Color15=#cdd6f4\n"));
        assert!(!single.contains("[Dark]"));

        assert_eq!(builtin(&mocha, None), Some("Catppuccin Mocha"));
        assert_eq!(builtin(&mocha, Some((&latte, &mocha))), None);
        let (g_light, g_dark) = (p("gruvbox-light"), p("gruvbox-dark"));
        assert_eq!(builtin(&g_dark, Some((&g_light, &g_dark))), Some("Gruvbox"));
        assert_eq!(builtin(&p("one-dark"), None), None);

        let pair = render(&mocha, Some((&latte, &mocha)));
        let (_, dark) = pair.split_once("[Dark]\n").unwrap();
        assert!(pair.contains("[Light]\nBackground=#eff1f5\n"));
        assert!(dark.starts_with("Background=#1e1e2e\n"));
    }
}
