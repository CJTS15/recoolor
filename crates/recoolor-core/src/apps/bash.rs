//! bash's prompt: `~/.bashrc.d/recoolor.sh`, which Fedora's default `.bashrc` reads,
//! sets `PS1` in the palette's colors (24-bit, so every terminal shows the same). Open
//! shells read it again at their next prompt once Recoolor rewrites it, which it does
//! on every change, light/dark switches included. A prompt from oh-my-posh or starship
//! is left alone.

use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::ApplyError;
use crate::color::Color;
use crate::palette::Palette;

pub fn path(home: &Path) -> PathBuf {
    home.join(".bashrc.d/recoolor.sh")
}

/// Why `bashrc` would not show Recoolor's prompt, if it would not.
pub fn unusable(bashrc: &str) -> Option<&'static str> {
    let lines = || {
        bashrc
            .lines()
            .map(str::trim)
            .filter(|l| !l.starts_with('#'))
    };
    if !lines().any(|l| l.contains(".bashrc.d")) {
        return Some("~/.bashrc does not read ~/.bashrc.d");
    }
    if lines().any(|l| l.contains("oh-my-posh init") || l.contains("starship init")) {
        return Some("the prompt comes from oh-my-posh or starship");
    }
    None
}

pub fn render(palette: &Palette) -> String {
    let c = &palette.colors;
    // `\[ \]` tell bash the escapes take no room, so line editing stays right.
    let fg = |color: Color| format!("\\[\\e[38;2;{};{};{}m\\]", color.r, color.g, color.b);
    let reset = "\\[\\e[0m\\]";
    format!(
        "\
# Generated by Recoolor from {id}. Reset in Recoolor (or `recoolor restore`) removes it.
[[ $- == *i* ]] || return
PS1='{user}\\u@\\h{reset} {dir}\\w{reset} {mark}\\${reset} '
# Read again at the next prompt once Recoolor rewrites this file, so open shells follow.
__recoolor_file=${{BASH_SOURCE[0]}}
__recoolor_seen=$(stat -c %.9Y \"$__recoolor_file\" 2>/dev/null)
__recoolor_reload() {{
    local now
    now=$(stat -c %.9Y \"$__recoolor_file\" 2>/dev/null) || return
    [[ $now == \"$__recoolor_seen\" ]] || source \"$__recoolor_file\"
}}
[[ $PROMPT_COMMAND == *__recoolor_reload* ]] || PROMPT_COMMAND=\"__recoolor_reload${{PROMPT_COMMAND:+;$PROMPT_COMMAND}}\"
",
        id = palette.id,
        user = fg(c.green),
        dir = fg(c.blue),
        mark = fg(c.overlay),
    )
}

pub fn write(home: &Path, palette: &Palette) -> Result<(), ApplyError> {
    write_owned(&path(home), &render(palette))
}

pub fn remove(home: &Path) -> Result<bool, ApplyError> {
    remove_owned(&path(home))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn prompt_in_the_palette() {
        let mocha = bundled()
            .into_iter()
            .find(|p| p.id == "catppuccin-mocha")
            .unwrap();
        let text = render(&mocha);
        assert!(text.starts_with("# Generated by Recoolor from catppuccin-mocha."));
        // Green user@host, blue folder.
        assert!(text.contains(
            "PS1='\\[\\e[38;2;166;227;161m\\]\\u@\\h\\[\\e[0m\\] \\[\\e[38;2;137;180;250m\\]\\w"
        ));
        assert!(
            text.contains(
                "PROMPT_COMMAND=\"__recoolor_reload${PROMPT_COMMAND:+;$PROMPT_COMMAND}\""
            )
        );
    }

    #[test]
    fn only_a_bashrc_that_reads_bashrc_d() {
        let fedora = "if [ -d ~/.bashrc.d ]; then\n    for rc in ~/.bashrc.d/*; do\n";
        assert_eq!(unusable(fedora), None);
        assert!(unusable("alias ll='ls -l'\n").is_some());
        assert!(unusable(&format!("{fedora}eval \"$(oh-my-posh init bash)\"\n")).is_some());
        assert_eq!(
            unusable(&format!("{fedora}# eval \"$(starship init bash)\"\n")),
            None
        );
    }
}
