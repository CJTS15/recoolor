//! The systemd user unit that runs `recoolor watch`, which rewrites the GTK3 stylesheet
//! when GNOME switches between light and dark. Writing and removing the file lives
//! here; starting and stopping it with `systemctl` is the app's job.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::apply::{ApplyError, io_err, write_atomic};

pub const UNIT_NAME: &str = "recoolor-watch.service";
const MARKER: &str = "# Generated by Recoolor";

/// `$XDG_CONFIG_HOME/systemd/user/recoolor-watch.service`.
pub fn unit_path(config_home: &Path) -> PathBuf {
    config_home.join("systemd/user").join(UNIT_NAME)
}

/// The unit file text for running `exe watch`.
pub fn unit(exe: &str) -> String {
    // systemd unquotes `\` and `"` inside quotes, and expands `%` specifiers.
    // Uninstalled without `recoolor restore`: skip instead of failing at login.
    let condition = exe.replace('%', "%%");
    let exe = exe
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    format!(
        "{MARKER}. `recoolor restore` removes it.\n\
         [Unit]\n\
         Description=Recoolor: keep themes in step with GNOME's light/dark style and accent\n\
         PartOf=graphical-session.target\n\
         ConditionPathExists={condition}\n\
         After=graphical-session.target\n\
         \n\
         [Service]\n\
         ExecStart=\"{exe}\" watch\n\
         Restart=on-failure\n\
         \n\
         [Install]\n\
         WantedBy=graphical-session.target\n"
    )
}

/// Writes the unit, replacing an older one of Recoolor's but never someone else's.
pub fn install(config_home: &Path, exe: &str) -> Result<(), ApplyError> {
    let path = unit_path(config_home);
    if is_foreign(&path)? {
        return Err(ApplyError::Foreign { path });
    }
    write_atomic(&path, &unit(exe))
}

/// Removes Recoolor's unit. Returns whether there was one; a foreign file is left alone.
pub fn remove(config_home: &Path) -> Result<bool, ApplyError> {
    let path = unit_path(config_home);
    match fs::read_to_string(&path) {
        Ok(text) if text.starts_with(MARKER) => {
            fs::remove_file(&path).map_err(io_err(&path))?;
            Ok(true)
        }
        Ok(_) => Ok(false),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(io_err(&path)(e)),
    }
}

pub fn is_installed(config_home: &Path) -> bool {
    fs::read_to_string(unit_path(config_home)).is_ok_and(|text| text.starts_with(MARKER))
}

fn is_foreign(path: &Path) -> Result<bool, ApplyError> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(!text.starts_with(MARKER)),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
        // Unreadable or not UTF-8: not ours, so not ours to replace.
        Err(_) => Ok(true),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotes_paths_with_spaces_and_specials() {
        let text = unit("/home/me/My Apps/pi%n\"ta");
        assert!(text.contains("ExecStart=\"/home/me/My Apps/pi%%n\\\"ta\" watch\n"));
        assert!(text.contains("ConditionPathExists=/home/me/My Apps/pi%%n\"ta\n"));
    }

    #[test]
    fn install_and_remove_only_touch_recoolors_unit() {
        let home = tempfile::tempdir().unwrap();
        install(home.path(), "/usr/bin/recoolor").unwrap();
        assert!(is_installed(home.path()));
        install(home.path(), "/opt/recoolor").unwrap();
        assert!(remove(home.path()).unwrap());
        assert!(!unit_path(home.path()).exists());
        assert!(!remove(home.path()).unwrap());

        let path = unit_path(home.path());
        fs::write(&path, "[Service]\nExecStart=/bin/true\n").unwrap();
        assert!(matches!(
            install(home.path(), "/usr/bin/recoolor"),
            Err(ApplyError::Foreign { .. })
        ));
        assert!(!remove(home.path()).unwrap());
        assert!(path.exists());
    }
}
