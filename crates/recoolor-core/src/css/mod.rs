//! CSS generation for the user stylesheets GTK loads from `~/.config/gtk-{3,4}.0/gtk.css`.

mod gtk3;
mod gtk4;
mod shell;

pub use gtk3::{gtk3, gtk3_adw};
pub use gtk4::{gtk4, gtk4_pair};
pub use shell::{
    searchlight, shell, shell_blur, shell_high_contrast, shell_popups, switcher_labels,
};

use crate::color::Color;
use crate::palette::{Palette, Variant};

/// First line of every file Recoolor writes. Used to recognise our own files, so the
/// user's hand-written CSS is never overwritten or deleted.
pub const MARKER: &str = "/* Generated by Recoolor";

/// Joins the two ids in a light/dark pair's marker. Palette ids cannot contain it.
pub const PAIR_SEPARATOR: char = '+';

/// `id` is a palette id, or a light and a dark id joined by [`PAIR_SEPARATOR`].
pub(crate) fn header(id: &str) -> String {
    format!(
        "{MARKER}: palette={id} */\n\
         /* Edits here are lost on the next apply. Run `recoolor restore` to bring back the\n   \
         gtk.css you had before Recoolor. */\n\n"
    )
}

/// Reads the id from the header back from a file Recoolor generated, or `None` for any
/// other file. For a light/dark pair this is both ids joined by [`PAIR_SEPARATOR`].
pub fn applied_palette_id(css: &str) -> Option<&str> {
    let first = css.lines().next()?;
    first
        .strip_prefix(MARKER)?
        .strip_prefix(": palette=")?
        .strip_suffix(" */")
}

/// Colors derived from a palette that both toolkits share.
pub(crate) struct Roles {
    pub accent_fg: Color,
    pub destructive_fg: Color,
    pub success_fg: Color,
    pub warning_fg: Color,
    pub hover: Color,
    pub active: Color,
    pub border: Color,
    /// Cards, boxed lists and popovers: a step lighter than the window in both
    /// styles, as Adwaita's are (white on near-white in light style). A light
    /// palette's `surface` is darker than its window, so light style lifts the
    /// window toward white instead.
    pub card: Color,
    /// Tint for drop shadows, separators and shading under header bars: dark in both
    /// styles, as Adwaita's is, since a light palette's `crust` is a pale grey that
    /// would not show.
    pub shade: Color,
    /// Alpha for `shade`. 10% in light style: a palette's text is lighter than
    /// Adwaita's near-black, which it draws at 7%.
    pub shade_alpha: f32,
}

impl Roles {
    pub fn new(palette: &Palette) -> Self {
        let c = &palette.colors;
        let dark = palette.variant == Variant::Dark;
        let fg_on = |bg: Color| bg.best_foreground(&[c.crust, c.base, c.text]);
        Self {
            accent_fg: fg_on(c.accent),
            destructive_fg: fg_on(c.red),
            success_fg: fg_on(c.green),
            warning_fg: fg_on(c.yellow),
            hover: c.surface.mix(c.overlay, 0.25),
            active: c.surface.mix(c.overlay, 0.45),
            border: c.surface.mix(c.overlay, if dark { 0.2 } else { 0.5 }),
            card: if dark {
                c.surface
            } else {
                c.base.mix(Color::rgb(255, 255, 255), 0.6)
            },
            shade: if dark { c.crust } else { c.text },
            shade_alpha: if dark { 0.36 } else { 0.10 },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::{Variant, bundled};

    #[test]
    fn header_round_trips_palette_id() {
        for p in bundled() {
            for css in [gtk3(&p), gtk4(&p)] {
                assert_eq!(applied_palette_id(&css), Some(p.id.as_str()));
            }
        }
        let [latte, mocha] = ["catppuccin-latte", "catppuccin-mocha"]
            .map(|id| bundled().into_iter().find(|p| p.id == id).unwrap());
        assert_eq!(
            applied_palette_id(&gtk4_pair(&latte, &mocha)),
            Some("catppuccin-latte+catppuccin-mocha")
        );
    }

    #[test]
    fn foreign_css_has_no_palette_id() {
        assert_eq!(applied_palette_id("window { color: red; }"), None);
        assert_eq!(applied_palette_id(""), None);
    }

    #[test]
    fn accent_foreground_is_readable() {
        for p in bundled() {
            let ratio = Roles::new(&p).accent_fg.contrast(p.colors.accent);
            assert!(ratio >= 3.0, "{}: accent fg contrast {ratio}", p.id);
        }
    }

    /// Recoolor's own palettes keep their upstream colors, even where a hue falls a
    /// little under 4.5:1 as text. Gogh palettes are nudged by the importer instead.
    const WEAK_TEXT: [&str; 1] = ["tokyo-night-day"];

    #[test]
    fn text_colors_are_readable_on_the_window() {
        let mut weak = Vec::new();
        for p in bundled() {
            let c = &p.colors;
            let dark = p.variant == Variant::Dark;
            for (role, fill) in [
                ("accent", c.accent),
                ("red", c.red),
                ("green", c.green),
                ("yellow", c.yellow),
            ] {
                let ratio = fill.standalone(dark).contrast(c.base);
                if ratio < 4.5 && !WEAK_TEXT.contains(&p.id.as_str()) {
                    weak.push(format!("{} {role}: {ratio:.2}", p.id));
                }
            }
        }
        assert!(weak.is_empty(), "{weak:#?}");
    }

    /// Upstream colors kept in Recoolor's own palettes: a success or warning fill
    /// just under 3:1 with its best label, or text under 4.5:1 on cards.
    const WEAK_FILLS: [&str; 4] = [
        "catppuccin-latte",
        "everforest-light",
        "solarized-dark",
        "solarized-light",
    ];

    #[test]
    fn status_fills_and_cards_are_readable() {
        let mut weak = Vec::new();
        for p in bundled() {
            let (c, r) = (&p.colors, Roles::new(&p));
            for (role, fill, fg) in [
                ("destructive", c.red, r.destructive_fg),
                ("success", c.green, r.success_fg),
                ("warning", c.yellow, r.warning_fg),
            ] {
                let ratio = fill.contrast(fg);
                if ratio < 3.0 {
                    weak.push(format!("{} {role} fill: {ratio:.2}", p.id));
                }
            }
            let ratio = c.text.contrast(r.card);
            if ratio < 4.5 {
                weak.push(format!("{} text on card: {ratio:.2}", p.id));
            }
        }
        weak.retain(|w| !WEAK_FILLS.iter().any(|id| w.starts_with(&format!("{id} "))));
        assert!(weak.is_empty(), "{weak:#?}");
    }

    #[test]
    fn separators_show_in_light_palettes() {
        let mut faint = Vec::new();
        for p in bundled()
            .into_iter()
            .filter(|p| p.variant == Variant::Light)
        {
            let r = Roles::new(&p);
            let separator = r.card.mix(r.shade, r.shade_alpha);
            let ratio = separator.contrast(r.card);
            if ratio < 1.1 {
                faint.push(format!("{}: {ratio:.3}", p.id));
            }
        }
        assert!(faint.is_empty(), "{faint:#?}");
    }

    #[test]
    fn output_has_balanced_braces() {
        for p in bundled() {
            for css in [gtk3(&p), gtk4(&p), gtk4_pair(&p, &p)] {
                assert_eq!(
                    css.matches('{').count(),
                    css.matches('}').count(),
                    "{}",
                    p.id
                );
            }
        }
    }
}
