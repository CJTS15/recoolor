//! Firefox: `chrome/pinta.css` in each profile sets the color variables that
//! firefox-gnome-theme (`--gnome-*`) and Catppuccin-style userChrome files
//! (`--ctp-*`) read, and one marked `@import` line in `userChrome.css` loads it
//! after them. Firefox reads userChrome at startup, so it needs a restart; it also
//! needs `toolkit.legacyUserProfileCustomizations.stylesheets` turned on.

use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use super::{remove_owned, write_owned};
use crate::apply::{ApplyError, io_err, read_or_empty, write_atomic};
use crate::palette::Palette;

const IMPORT: &str = "@import \"pinta.css\"; /* Added by Pinta; Reset removes it. */";

/// Profile folders listed in `profiles.ini` under the Firefox roots in `home`
/// (`~/.mozilla/firefox`, and `~/.config/mozilla/firefox` used by newer releases).
pub fn profiles(home: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for root in [
        home.join(".mozilla/firefox"),
        home.join(".config/mozilla/firefox"),
    ] {
        let Ok(ini) = fs::read_to_string(root.join("profiles.ini")) else {
            continue;
        };
        for section in ini
            .split("\n[")
            .filter(|s| s.trim_start_matches('[').starts_with("Profile"))
        {
            let value = |key: &str| {
                section
                    .lines()
                    .find_map(|l| l.strip_prefix(key)?.strip_prefix('='))
                    .map(str::trim)
            };
            let Some(path) = value("Path") else { continue };
            let dir = if value("IsRelative") == Some("0") {
                PathBuf::from(path)
            } else {
                root.join(path)
            };
            if dir.is_dir() && !found.contains(&dir) {
                found.push(dir);
            }
        }
    }
    found
}

pub fn css_path(profile: &Path) -> PathBuf {
    profile.join("chrome/pinta.css")
}

fn user_chrome(profile: &Path) -> PathBuf {
    profile.join("chrome/userChrome.css")
}

pub fn render(palette: &Palette) -> String {
    let c = &palette.colors;
    let mut css = format!("/* Generated by Pinta from {} */\n:root {{\n", palette.id);
    let vars = [
        // Catppuccin-style userChrome files.
        ("--ctp-rosewater", c.pink),
        ("--ctp-flamingo", c.pink),
        ("--ctp-pink", c.pink),
        ("--ctp-mauve", c.purple),
        ("--ctp-red", c.red),
        ("--ctp-maroon", c.red),
        ("--ctp-peach", c.orange),
        ("--ctp-yellow", c.yellow),
        ("--ctp-green", c.green),
        ("--ctp-teal", c.teal),
        ("--ctp-sky", c.teal),
        ("--ctp-sapphire", c.blue),
        ("--ctp-blue", c.blue),
        ("--ctp-lavender", c.accent),
        ("--ctp-text", c.text),
        ("--ctp-subtext1", c.subtext),
        ("--ctp-subtext0", c.subtext.mix(c.overlay, 0.5)),
        ("--ctp-overlay2", c.overlay.mix(c.subtext, 0.5)),
        ("--ctp-overlay1", c.overlay.mix(c.subtext, 0.25)),
        ("--ctp-overlay0", c.overlay),
        ("--ctp-surface2", c.surface.mix(c.overlay, 0.5)),
        ("--ctp-surface1", c.surface.mix(c.overlay, 0.25)),
        ("--ctp-surface0", c.surface),
        ("--ctp-base", c.base),
        ("--ctp-mantle", c.mantle),
        ("--ctp-crust", c.crust),
        // firefox-gnome-theme.
        ("--gnome-window-background", c.base),
        ("--gnome-window-color", c.text),
        ("--gnome-view-background", c.mantle),
        ("--gnome-sidebar-background", c.mantle),
        ("--gnome-secondary-sidebar-background", c.base),
        ("--gnome-headerbar-background", c.mantle),
        ("--gnome-menu-background", c.surface),
        ("--gnome-card-background", c.surface),
        ("--gnome-tabbar-identity-color-blue", c.blue),
        ("--gnome-tabbar-identity-color-green", c.green),
        ("--gnome-tabbar-identity-color-yellow", c.yellow),
        ("--gnome-tabbar-identity-color-orange", c.orange),
        ("--gnome-tabbar-identity-color-red", c.red),
        ("--gnome-tabbar-identity-color-purple", c.purple),
    ];
    for (name, color) in vars {
        let _ = writeln!(css, "  {name}: {color} !important;");
    }
    css.push_str("}\n");
    css
}

/// Adds the import after the file's existing `@import`s (CSS wants them first).
fn add_import(text: &str) -> String {
    if text.lines().any(|l| l.trim() == IMPORT) {
        return text.to_owned();
    }
    let mut lines: Vec<&str> = text.lines().collect();
    let at = lines
        .iter()
        .rposition(|l| l.trim_start().starts_with("@import"))
        .map_or(0, |i| i + 1);
    lines.insert(at, IMPORT);
    lines.join("\n") + "\n"
}

fn remove_import(text: &str) -> String {
    let kept: Vec<&str> = text.lines().filter(|l| l.trim() != IMPORT).collect();
    if kept.iter().all(|l| l.trim().is_empty()) {
        return String::new();
    }
    kept.join("\n") + "\n"
}

pub fn is_applied(profile: &Path) -> bool {
    super::is_pintas(&css_path(profile))
}

pub fn apply(profile: &Path, palette: &Palette) -> Result<(), ApplyError> {
    write_owned(&css_path(profile), &render(palette))?;
    let path = user_chrome(profile);
    let text = read(&path)?;
    let with = add_import(&text);
    if with != text {
        write_atomic(&path, &with)?;
    }
    Ok(())
}

pub fn remove(profile: &Path) -> Result<(), ApplyError> {
    remove_owned(&css_path(profile))?;
    let path = user_chrome(profile);
    let text = read(&path)?;
    let without = remove_import(&text);
    if without == text {
        return Ok(());
    }
    if without.is_empty() {
        // Pinta created this file to hold the import.
        return fs::remove_file(&path).map_err(io_err(&path));
    }
    write_atomic(&path, &without)
}

fn read(path: &Path) -> Result<String, ApplyError> {
    read_or_empty(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette::bundled;

    #[test]
    fn import_goes_after_imports_and_comes_back_out() {
        let user = "@import \"firefox-gnome-theme/userChrome.css\";\n#nav-bar { color: red; }\n";
        let with = add_import(user);
        assert_eq!(
            with,
            format!(
                "@import \"firefox-gnome-theme/userChrome.css\";\n{IMPORT}\n#nav-bar {{ color: red; }}\n"
            )
        );
        assert_eq!(add_import(&with), with);
        assert_eq!(remove_import(&with), user);
        assert_eq!(remove_import(&add_import("")), "");
    }

    #[test]
    fn finds_relative_and_absolute_profiles() {
        let home = tempfile::tempdir().unwrap();
        let root = home.path().join(".mozilla/firefox");
        let abs = home.path().join("elsewhere");
        for dir in [root.join("a.default"), abs.clone()] {
            fs::create_dir_all(dir).unwrap();
        }
        fs::write(
            root.join("profiles.ini"),
            format!(
                "[Profile1]\nName=x\nIsRelative=1\nPath=a.default\n\n[Profile0]\nIsRelative=0\nPath={}\n\n[Profile2]\nIsRelative=1\nPath=missing\n\n[General]\nVersion=2\n",
                abs.display()
            ),
        )
        .unwrap();
        assert_eq!(profiles(home.path()), [root.join("a.default"), abs]);
    }

    #[test]
    fn apply_and_remove_leave_users_file_as_it_was() {
        let profile = tempfile::tempdir().unwrap();
        let user = "@import \"firefox-gnome-theme/userChrome.css\";\n";
        fs::create_dir_all(profile.path().join("chrome")).unwrap();
        fs::write(user_chrome(profile.path()), user).unwrap();
        let mocha = bundled()
            .into_iter()
            .find(|p| p.id == "catppuccin-mocha")
            .unwrap();

        apply(profile.path(), &mocha).unwrap();
        assert!(is_applied(profile.path()));
        assert!(render(&mocha).contains("  --ctp-base: #1e1e2e !important;\n"));
        remove(profile.path()).unwrap();
        assert!(!css_path(profile.path()).exists());
        assert_eq!(
            fs::read_to_string(user_chrome(profile.path())).unwrap(),
            user
        );
    }
}
